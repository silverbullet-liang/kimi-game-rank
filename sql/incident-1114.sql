## 三、为什么没挡住：三个设计缺口

**一、人机验证的通道可以被告知。** 请求里带一个通道参数，就能让校验走那条比较弱的通道，强通道全程不参与。

**二、限流按单个来源计数。** 一个账号换一个来源地址，单个来源的次数上限永远碰不到。

**三、注册不要求邮箱。** 180 个账号零绑邮箱，唯一需要外部成本的环节被跳过。

三个缺口单独都不致命，叠在一起就是一条完整的通道。

